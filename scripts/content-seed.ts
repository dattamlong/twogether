import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ACHIEVEMENTS, COUPLE_QUESTS, DAILY_QUESTS, SHOP_ITEMS } from "../src/content/catalog";
import { CATEGORIES, type Question } from "../src/content/schema";
import { ROOM_DEPTH, ROOM_WIDTH, reservedTiles } from "../src/game/world/room";
import { loadContent } from "./content-check";

const lit = (value: unknown): string => {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
};
const json = (value: unknown) => (value === undefined || value === null ? "null" : `${lit(JSON.stringify(value))}::jsonb`);
const textArray = (values: string[]) => `array[${values.map(lit).join(", ")}]::text[]`;
const insert = (table: string, columns: string[], rows: unknown[][]) =>
  rows.length === 0
    ? ""
    : `insert into public.${table} (${columns.join(", ")}) values\n${rows.map((r) => `  (${r.join(", ")})`).join(",\n")};\n`;

const CATEGORY_INFO: Record<(typeof CATEGORIES)[number], [string, string, string]> = {
  vocabulary: ["Vocabulary", "Từ vựng", "Learn words you can use every day."],
  grammar: ["Grammar", "Ngữ pháp", "Build sentences that sound natural."],
  listening: ["Listening", "Nghe", "Train your ear with short clips."],
  writing: ["Writing", "Viết", "Put words in order and write clearly."],
  speaking: ["Speaking", "Nói", "Listen, repeat and record yourself."],
};

const questionRow = (q: Question, lessonId: string, position: number, level: string) => {
  const answers = q.kind === "sentence_order" ? q.answers : [q.answer];
  return [
    lit(q.id),
    lit(lessonId),
    position,
    lit(q.kind),
    lit(level),
    lit(q.objective),
    lit(q.prompt),
    lit(q.prompt_vi ?? null),
    json(q.kind === "sentence_order" ? null : q.options),
    json(q.kind === "sentence_order" ? q.tokens : null),
    lit(q.kind === "listening" ? q.audio_text : null),
    lit(q.kind === "sentence_order" ? q.hint : null),
    lit(q.kind === "sentence_order" ? q.hint_vi : null),
    lit(q.kind === "multiple_choice" ? (q.word?.term ?? null) : null),
    json(answers),
    lit(q.explanation),
    lit(q.explanation_vi),
    json(q.kind === "multiple_choice" ? (q.word ?? null) : null),
  ];
};

export function buildSeed() {
  const { lessons, loveQuestions, errors } = loadContent();
  if (errors.length) throw new Error(`Content invalid:\n${errors.join("\n")}`);

  const levelOrder = ["A1", "A2", "B1", "B2", "C1"];
  const sortedLessons = [...lessons].sort(
    (a, b) =>
      CATEGORIES.indexOf(a.category) - CATEGORIES.indexOf(b.category) ||
      levelOrder.indexOf(a.level) - levelOrder.indexOf(b.level) ||
      a.slug.localeCompare(b.slug),
  );

  const parts = [
    "-- Generated by scripts/content-seed.ts. Do not edit by hand.",
    insert(
      "learning_categories",
      ["id", "name", "name_vi", "description", "sort_order"],
      CATEGORIES.map((c, i) => [lit(c), ...CATEGORY_INFO[c].map(lit), i]),
    ),
    insert(
      "lessons",
      ["id", "category_id", "level", "topic", "title", "title_vi", "objectives", "sort_order"],
      sortedLessons.map((l, i) => [lit(l.slug), lit(l.category), lit(l.level), lit(l.topic), lit(l.title), lit(l.title_vi), textArray(l.objectives), i]),
    ),
    insert(
      "lesson_questions",
      ["id", "lesson_id", "position", "kind", "level", "objective", "prompt", "prompt_vi", "options", "tokens", "audio_text", "hint", "hint_vi", "word_term", "answers", "explanation", "explanation_vi", "word"],
      sortedLessons.flatMap((l) => l.questions.map((q, i) => questionRow(q, l.slug, i + 1, l.level))),
    ),
    insert(
      "daily_love_questions",
      ["id", "prompt", "prompt_vi", "helper_phrase", "sort_order"],
      loveQuestions.map((q, i) => [lit(q.id), lit(q.prompt), lit(q.prompt_vi), lit(q.helper_phrase ?? null), i]),
    ),
    insert(
      "shop_items",
      ["id", "name", "name_vi", "description", "category", "price", "asset_key", "footprint_w", "footprint_h", "min_home_level", "shop_visible"],
      SHOP_ITEMS.map((s) => [lit(s.id), lit(s.name), lit(s.name_vi), lit(s.description), lit(s.category), s.price, lit(s.asset_key), s.footprint_w, s.footprint_h, s.min_home_level, s.shop_visible]),
    ),
    insert(
      "daily_quests",
      ["id", "slot", "title", "title_vi", "event", "category", "target", "xp_reward", "coin_reward"],
      DAILY_QUESTS.map((q) => [lit(q.id), lit(q.slot), lit(q.title), lit(q.title_vi), lit(q.event), lit(q.category), q.target, q.xp_reward, q.coin_reward]),
    ),
    insert(
      "couple_quests",
      ["id", "title", "title_vi", "description", "mode", "event", "target", "couple_xp", "love_energy", "coin_reward"],
      COUPLE_QUESTS.map((q) => [lit(q.id), lit(q.title), lit(q.title_vi), lit(q.description), lit(q.mode), lit(q.event), q.target, q.couple_xp, q.love_energy, q.coin_reward]),
    ),
    insert(
      "achievements",
      ["id", "scope", "title", "title_vi", "description", "icon", "coin_reward", "reward_item_id"],
      ACHIEVEMENTS.map((a) => [lit(a.id), lit(a.scope), lit(a.title), lit(a.title_vi), lit(a.description), lit(a.icon), a.coin_reward, lit(a.reward_item_id)]),
    ),
    insert("room_dimensions", ["width", "depth"], [[ROOM_WIDTH, ROOM_DEPTH]]),
    insert("room_reserved_tiles", ["x", "y"], reservedTiles().map((t) => [t.x, t.y])),
  ];
  return parts.join("\n");
}

if (process.argv[1] === import.meta.filename) {
  const sql = buildSeed();
  const target = join(import.meta.dirname, "..", "supabase", "seed.sql");
  writeFileSync(target, sql);
  console.log(`Wrote ${target} (${(sql.length / 1024).toFixed(0)} KB)`);
}
